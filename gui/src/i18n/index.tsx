const I18nContext = createContext<I18nContextValue | null>(null);

function resolveLocale(): Locale {
  if (typeof window === 'undefined') return 'zh-TW';
  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (stored === 'zh-TW' || stored === 'en') return stored;
  } catch {
    // SecurityError when storage is disabled — fall through to browser detection
  }
  const browserLocale = window.navigator.language.toLowerCase();
  return browserLocale.startsWith('zh') ? 'zh-TW' : 'en';
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return Object.entries(params).reduce(
    (result, [key, value]) => result.split(`{{${key}}}`).join(String(value)),
    template
  );
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => resolveLocale());

  useEffect(() => {
    try {
      if (typeof window !== 'undefined') {
        window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
      }
    } catch {
      // Storage unavailable — ignore
    }
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key: string, params?: Record<string, string | number>) => {
        const template = messages[locale][key] || messages['zh-TW'][key] || key;
        return interpolate(template, params);
      },
    }),
    [locale]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider');
  }
  return context;
}

export type { Locale };

/**
 * 獨立翻譯函式 — 供 Zustand store 等無法使用 React Hook 的場景呼叫。
 * 每次呼叫時從 localStorage 讀取當前語系，確保與 I18nProvider 同步。
 */
export function tRaw(key: string, params?: Record<string, string | number>): string {
  const locale = resolveLocale();
  const template = messages[locale][key] || messages['zh-TW'][key] || key;
  return interpolate(template, params);
}

